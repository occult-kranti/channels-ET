const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').resolve(__dirname, '../../dist/transcript-knowledge/vendor/minisearch.js'),'utf8'),context);
const MiniSearch=context.MiniSearch;assert.equal(typeof MiniSearch,'function');
const tokenize=text=>String(text).normalize('NFKC').match(/[\p{L}\p{M}\p{N}]+(?:['’][\p{L}\p{M}\p{N}]+)*/gu)||[];
const options={idField:'id',fields:['question','summary','metadata'],storeFields:['id','question','summary','metadata'],tokenize,processTerm:t=>t.toLowerCase(),searchOptions:{combineWith:'OR',prefix:false,fuzzy:false}};
const search=new MiniSearch(options);
search.addAll([{id:'a',question:'What does Mary recommend?',summary:'Contact will not happen now.',metadata:'Example written source'}, {id:'b',question:'What is an initiation?',summary:'Contact could happen later.',metadata:'Different example'}, {id:'c',question:'How is Krishna’s name written?',summary:'नमस्ते; energy 2031.',metadata:'Unicode example'}]);
assert.deepEqual(Array.from(search.search('not'),x=>x.id),['a']);
assert.equal(search.search('contact').length,2);
assert.equal(search.search('cont').length,0);
assert.equal(search.search('cont',{prefix:true}).length,2);
assert.equal(search.search('contcat').length,0);
assert.equal(search.search('missingword').length,0);
assert.equal(search.search('').length,0);
assert.deepEqual(Array.from(search.search('Krishna’s'),x=>x.id),['c']);
assert.deepEqual(Array.from(search.search('2031'),x=>x.id),['c']);
assert.equal(search.search('Mary initiation').length,2);
assert.deepEqual(tokenize('नमस्ते'),['नमस्ते']);
assert.deepEqual(Array.from(search.search('नमस्ते'),x=>x.id),['c']);
assert.throws(()=>search.add({id:'a',question:'Duplicate'}));
const restored=MiniSearch.loadJSON(JSON.stringify(search),options);assert.equal(restored.search('contact').length,2);
assert.equal(typeof context.fetch,'undefined');
console.log(JSON.stringify({status:'passed',checks:16,browser_umd_global:true,external_network_required:false,scope:'synthetic API/Unicode/negation-preservation/OR/prefix/duplicate/empty/roundtrip checks; no corpus retrieval-accuracy result'}));
